#!/usr/bin/env python3
"""Builds app/src/main/java/com/kurdikeyboard/EmojiData.java from Unicode's emoji-test.txt.

Usage: python tools/build_emoji.py path/to/emoji-test.txt
(download: https://www.unicode.org/Public/emoji/13.1/emoji-test.txt)

Keeps fully-qualified emoji, drops skin-tone variants and the Component group.
Version 13.1 so most phones of the last years can draw them; the app also hides
any emoji the phone's font cannot draw.
"""
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "app/src/main/java/com/kurdikeyboard/EmojiData.java"
KEEP = ["Smileys & Emotion", "People & Body", "Animals & Nature", "Food & Drink", "Activities",
        "Travel & Places", "Objects", "Symbols", "Flags"]

groups = {}
cur = None
for line in open(sys.argv[1], encoding="utf-8"):
    if line.startswith("# group:"):
        cur = groups.setdefault(line.split(":", 1)[1].strip(), [])
        continue
    if not line.strip() or line.startswith("#"):
        continue
    codes, rest = line.split(";", 1)
    if "fully-qualified" not in rest.split("#")[0]:
        continue
    cps = [int(c, 16) for c in codes.split()]
    if any(0x1F3FB <= c <= 0x1F3FF for c in cps):
        continue
    cur.append("".join(chr(c) for c in cps))


def java_string(s):
    out = []
    for ch in s:
        if ch in "\\\"":
            out.append("\\" + ch)
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


lines = ["package com.kurdikeyboard;", "",
         "/** Emoji by group, from Unicode emoji-test.txt 13.1 (fully-qualified, no skin-tone variants)."
         " Generated by tools/build_emoji.py, do not edit. */",
         "final class EmojiData {", "    private EmojiData() {}", "",
         "    /** each entry: emoji separated by a single space */",
         "    static final String[] GROUPS = {"]
total = 0
for k in KEEP:
    e = groups[k]
    total += len(e)
    s = " ".join(e)
    parts = [s[i:i + 1500] for i in range(0, len(s), 1500)]
    # never split inside a surrogate pair / sequence: cut on spaces
    parts, buf = [], ""
    for em in e:
        if len(buf) + len(em) + 1 > 1500:
            parts.append(buf)
            buf = ""
        buf = em if not buf else buf + " " + em
    parts.append(buf)
    lines.append("        // %s (%d)" % (k, len(e)))
    lines.append("        " + " + \" \" +\n            ".join(java_string(p) for p in parts) + ",")
lines += ["    };", "}", ""]
OUT.write_text("\n".join(lines), encoding="utf-8")
print("emoji:", total)
